#!/usr/bin/env bash
# Build the Tell Me. Mac app (Apple Silicon): frontend/dist/Tell-Me-mac-arm64.zip
#
#   ./scripts/build-desktop.sh
#
# Steps:
#   1. backend/desktop.env  ← only public settings from backend/.env (it ships inside the app!)
#   2. backend binary       ← PyInstaller (backend/backend-service.spec)
#   3. bundled Redis        ← Redis Stack's redis-server + RediSearch module + OpenSSL, relinked
#   4. frontend + Electron  ← next build (static export) + electron-builder
#
# Needs: macOS on Apple Silicon, backend/.venv, Node 22, `brew install --cask redis-stack-server`.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BACKEND="$ROOT/backend"
FRONTEND="$ROOT/frontend"
REDIS_OUT="$FRONTEND/resources/redis"

say() { printf '\n\033[1;34m▸ %s\033[0m\n' "$*"; }
die() { printf '\n\033[1;31m✖ %s\033[0m\n' "$*" >&2; exit 1; }

[[ "$(uname -s)" == "Darwin" && "$(uname -m)" == "arm64" ]] || die "Build on an Apple Silicon Mac."
[[ -x "$BACKEND/.venv/bin/python" ]] || die "Missing backend/.venv (see CLAUDE.md)."

# ── 1. desktop.env: whitelist only settings that are safe to ship ────────────
say "Writing backend/desktop.env (public settings only)"
SAFE_KEYS=(SUPABASE_URL SUPABASE_ANON_KEY LLM_MODEL MAX_UPLOAD_MB BACKEND_ENCRYPTION_KEY)
[[ -f "$BACKEND/.env" ]] || die "Missing backend/.env to read SUPABASE_URL / SUPABASE_ANON_KEY from."
{
  echo "# Generated by scripts/build-desktop.sh. EVERYTHING HERE IS READABLE BY ANYONE WHO INSTALLS THE APP."
  for key in "${SAFE_KEYS[@]}"; do
    line="$(grep -E "^${key}=" "$BACKEND/.env" | tail -1 || true)"
    [[ -n "$line" ]] && echo "$line"
  done
} > "$BACKEND/desktop.env"
grep -q '^SUPABASE_URL=' "$BACKEND/desktop.env" || die "backend/.env has no SUPABASE_URL."
grep -q '^SUPABASE_ANON_KEY=' "$BACKEND/desktop.env" || die "backend/.env has no SUPABASE_ANON_KEY."
echo "  included keys: $(grep -oE '^[A-Z_]+' "$BACKEND/desktop.env" | tr '\n' ' ')"
if grep -qiE 'service_role|SERVICE_ROLE|JWT_SECRET' "$BACKEND/desktop.env"; then
  die "desktop.env would contain a secret. Aborting."
fi

# ── 2. Backend binary ────────────────────────────────────────────────────────
if [[ "${SKIP_BACKEND:-0}" == "1" && -x "$BACKEND/dist/backend-service/backend-service" ]]; then
  say "Reusing the existing backend build (SKIP_BACKEND=1)"
else
  say "Building the backend with PyInstaller (takes a few minutes)"
  "$BACKEND/.venv/bin/python" -m pip install --quiet --upgrade "pyinstaller>=6.16"
  ( cd "$BACKEND" && rm -rf build dist && .venv/bin/pyinstaller --noconfirm --log-level WARN backend-service.spec )
fi
[[ -x "$BACKEND/dist/backend-service/backend-service" ]] || die "PyInstaller did not produce the backend binary."

# ── 3. Bundled Redis with the search module ──────────────────────────────────
say "Bundling Redis Stack (redis-server + RediSearch)"
STACK_DIR="$(ls -d /opt/homebrew/Caskroom/redis-stack-server/*/ 2>/dev/null | sort -V | tail -1 || true)"
[[ -n "$STACK_DIR" && -x "$STACK_DIR/bin/redis-server" ]] || die "Install Redis Stack: brew install --cask redis-stack-server"
rm -rf "$REDIS_OUT" && mkdir -p "$REDIS_OUT"
cp "$STACK_DIR/bin/redis-server" "$STACK_DIR/lib/redisearch.so" "$REDIS_OUT/"
chmod u+w "$REDIS_OUT"/*

# Copy Homebrew OpenSSL next to the binaries and point them there (@loader_path), so users don't need Homebrew.
relink() {
  local file="$1"
  { otool -L "$file" | awk 'NR>1 {print $1}' | grep -E '^/opt/homebrew/|^/usr/local/' || true; } | while read -r dep; do
    local name; name="$(basename "$dep")"
    if [[ ! -f "$REDIS_OUT/$name" ]]; then
      cp "$dep" "$REDIS_OUT/$name" && chmod u+w "$REDIS_OUT/$name"
      install_name_tool -id "@loader_path/$name" "$REDIS_OUT/$name"
      relink "$REDIS_OUT/$name"
    fi
    install_name_tool -change "$dep" "@loader_path/$name" "$file"
  done
}
for f in "$REDIS_OUT"/redis-server "$REDIS_OUT"/redisearch.so; do relink "$f"; done
# install_name_tool invalidates signatures: re-sign ad hoc ONLY the files it changed.
# Untouched files (redisearch.so) keep Redis's own signature; re-signing it stops it loading.
for f in "$REDIS_OUT"/*; do
  codesign --verify "$f" >/dev/null 2>&1 || codesign --force --sign - "$f" >/dev/null 2>&1
done
if otool -L "$REDIS_OUT"/* | grep -E '/opt/homebrew/|/usr/local/' | grep -v ':$' >/dev/null; then die "Redis still links to Homebrew libraries."; fi

# Smoke test: the bundled Redis must start and offer FT.* (vector search).
PORT=6391
SMOKE_DIR="$(mktemp -d)"   # empty data dir: never load someone's dump.rdb
"$REDIS_OUT/redis-server" --port $PORT --bind 127.0.0.1 --save '' --dir "$SMOKE_DIR" --loadmodule "$REDIS_OUT/redisearch.so" --daemonize yes --pidfile /dev/null >/dev/null
# New binaries are scanned by macOS on first run, so allow time to start.
for _ in $(seq 1 30); do redis-cli -p $PORT PING >/dev/null 2>&1 && break; sleep 1; done
if ! redis-cli -p $PORT MODULE LIST 2>/dev/null | grep -q '^search$'; then
  redis-cli -p $PORT shutdown nosave >/dev/null 2>&1 || true
  die "Bundled Redis did not load RediSearch."
fi
redis-cli -p $PORT shutdown nosave >/dev/null 2>&1 || true
rm -rf "$SMOKE_DIR"
echo "  bundled Redis OK ($(du -sh "$REDIS_OUT" | cut -f1))"

# ── 4. Frontend + Electron ───────────────────────────────────────────────────
say "Building the frontend and packaging the app"
cd "$FRONTEND"
if [[ -s "$HOME/.nvm/nvm.sh" ]]; then . "$HOME/.nvm/nvm.sh" >/dev/null && nvm use 22 >/dev/null || true; fi
npm run build
npx electron-builder --mac zip --arm64

ZIP="$(ls "$FRONTEND"/dist/Tell-Me-mac-arm64.zip 2>/dev/null || true)"
[[ -n "$ZIP" ]] || die "electron-builder did not produce dist/Tell-Me-mac-arm64.zip"
say "Done: $ZIP ($(du -h "$ZIP" | cut -f1))"
echo "  Publish: gh release create vX.Y.Z \"$ZIP\" --title \"Tell Me vX.Y.Z\" --notes \"…\""
